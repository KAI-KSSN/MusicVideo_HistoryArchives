alter table public.work_types enable row level security;
alter table public.works enable row level security;
alter table public.music_video_details enable row level security;
alter table public.entities enable row level security;
alter table public.credit_roles enable row level security;
alter table public.work_credits enable row level security;
alter table public.taxonomy_categories enable row level security;
alter table public.taxonomy_terms enable row level security;
alter table public.work_taxonomy_terms enable row level security;
alter table public.awards enable row level security;
alter table public.award_categories enable row level security;
alter table public.work_award_results enable row level security;
alter table public.media_assets enable row level security;
alter table public.sources enable row level security;
alter table public.work_sources enable row level security;
