create policy "Public can read work types" on public.work_types for select to anon, authenticated using (true);
create policy "Public can read credit roles" on public.credit_roles for select to anon, authenticated using (true);
create policy "Public can read taxonomy categories" on public.taxonomy_categories for select to anon, authenticated using (true);
create policy "Public can read taxonomy terms" on public.taxonomy_terms for select to anon, authenticated using (true);
create policy "Public can read published works" on public.works for select to anon, authenticated using (status = 'published');

create policy "Public can read published music video details"
on public.music_video_details for select to anon, authenticated
using (exists (select 1 from public.works w where w.id = music_video_details.work_id and w.status = 'published'));

create policy "Public can read credited entities"
on public.entities for select to anon, authenticated
using (exists (
  select 1 from public.work_credits wc
  join public.works w on w.id = wc.work_id
  where wc.entity_id = entities.id and w.status = 'published'
));

create policy "Public can read published work credits"
on public.work_credits for select to anon, authenticated
using (exists (select 1 from public.works w where w.id = work_credits.work_id and w.status = 'published'));

create policy "Public can read published work taxonomy"
on public.work_taxonomy_terms for select to anon, authenticated
using (exists (select 1 from public.works w where w.id = work_taxonomy_terms.work_id and w.status = 'published'));

create policy "Public can read awards" on public.awards for select to anon, authenticated using (true);
create policy "Public can read award categories" on public.award_categories for select to anon, authenticated using (true);

create policy "Public can read published award results"
on public.work_award_results for select to anon, authenticated
using (exists (select 1 from public.works w where w.id = work_award_results.work_id and w.status = 'published'));

create policy "Public can read published media assets"
on public.media_assets for select to anon, authenticated
using (exists (select 1 from public.works w where w.id = media_assets.work_id and w.status = 'published'));

create policy "Public can read published curricula"
on public.curricula for select to anon, authenticated
using (status = 'published');

create policy "Public can read published curriculum items"
on public.curriculum_items for select to anon, authenticated
using (
  exists (select 1 from public.curricula c where c.id = curriculum_items.curriculum_id and c.status = 'published')
  and exists (select 1 from public.works w where w.id = curriculum_items.work_id and w.status = 'published')
);

create policy "Public can read published work relationships"
on public.work_relationships for select to anon, authenticated
using (
  exists (select 1 from public.works w where w.id = work_relationships.source_work_id and w.status = 'published')
  and exists (select 1 from public.works w where w.id = work_relationships.target_work_id and w.status = 'published')
);

commit;
